/** icon('heart', {size:22, fill:true, class:'x'}) */
export function icon(name, { size = 22, fill = false, cls = '', sw = 1.8 } = {}) {
  return h('svg', {
    class: `ic ${cls}`.trim(), width: size, height: size, viewBox: '0 0 24 24', 'aria-hidden': 'true', focusable: 'false',
    fill: fill ? 'currentColor' : 'none', stroke: 'currentColor', 'stroke-width': sw, 'stroke-linecap': 'round', 'stroke-linejoin': 'round',
    dangerouslySetInnerHTML: { __html: P[name] || '' },
  });
}

export function haptic(ms = 8) {
  try { navigator.vibrate && navigator.vibrate(ms); } catch { /* unsupported */ }
}

export function toast(msg, kind = 'info', ms = 2600) {
  bus.emit('toast', { msg, kind, ms });
}

/** await confirmDialog({title, message, confirmLabel, danger}) -> boolean */
export function confirmDialog(opts) {
  return new Promise((resolve) => bus.emit('confirm', { ...opts, resolve }));
}

export async function copyText(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch { /* fall through */ }
  const ta = document.createElement('textarea');
  ta.value = text;
  ta.setAttribute('readonly', '');
  ta.style.cssText = 'position:fixed;top:0;left:0;opacity:0;font-size:16px';
  document.body.appendChild(ta);
  ta.select();
  ta.setSelectionRange(0, text.length);
  let ok = false;
  try { ok = document.execCommand('copy'); } catch { /* ignore */ }
  ta.remove();
  return ok;
}

/** Subscribe to a bus event for the component's lifetime. */
export function useBus(evt, fn) {
  useEffect(() => bus.on(evt, fn), [evt, fn]);
}

export function triggerDownload(url, name) {
  const a = document.createElement('a');
  a.href = url;
  a.download = name || '';
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
}
